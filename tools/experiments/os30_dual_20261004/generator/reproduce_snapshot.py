#!/usr/bin/env python3
"""Reproduce a frozen private CPU recipe in a new directory; never overwrite it."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import tarfile


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def checked_log(command, path, cwd=None):
    with path.open("w") as log:
        subprocess.run(command, cwd=cwd, stdout=log, stderr=subprocess.STDOUT, check=True)


parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--snapshot", type=Path, required=True)
parser.add_argument("--profile", choices=["full-alu", "immediate"], default="full-alu")
parser.add_argument("--output", type=Path, help="New output directory; omit to verify snapshot hashes only")
parser.add_argument("--cache", type=Path, default=Path("tools/.vexii-home"))
args = parser.parse_args()
snapshot = args.snapshot.resolve()
recipe = json.loads((snapshot / "recipe.json").read_text())
for name, expected in recipe["file_sha256"].items():
    assert digest(snapshot / name) == expected, name
print(f"PASS: {len(recipe['file_sha256'])} frozen snapshot file hashes", flush=True)
if not args.output:
    raise SystemExit(0)

profile = recipe["profiles"][args.profile]
out = args.output.resolve()
out.mkdir(parents=True, exist_ok=False)
source = out / "source"
source.mkdir()
with tarfile.open(snapshot / profile["source_archive"], "r:gz") as archive:
    archive.extractall(source, filter="data")
for name, expected in profile["source_file_sha256"].items():
    assert digest(source / name) == expected, name

cache = args.cache.resolve()
assert cache.is_dir()
command = [
    "docker", "run", "--rm", "--user", f"{os.getuid()}:{os.getgid()}",
    "--env", "VEXIIRISCV_DEBUG_PARAM=0", "--env", "SPINALHDL_FROM_SOURCE=1",
    "-v", f"{out}:{out}", "-v", f"{cache}:/vexiihome",
    "--tmpfs", "/tmp:exec", "-w", str(source), recipe["docker_image_id"],
    "sbt", "-Duser.home=/vexiihome", "-Dsbt.boot.directory=/vexiihome/.sbt/boot",
    "-Dsbt.global.base=/vexiihome/.sbt", "-Dsbt.ivy.home=/vexiihome/.ivy2",
    "-Dsbt.server.forcestart=true", "--batch",
    "Test/runMain vexiiriscv.Generate " + " ".join(profile["flags"]),
]
checked_log(command, out / "generate.log")
generated = source / "VexiiRiscv.v"
raw = generated.read_text()
# The archived tree has no .git. Restore only the original nonfunctional
# provenance comment header; all remaining generated bytes must match exactly.
header, body = raw.split("\n\n", 1)
assert all(re.fullmatch(r"// (Generator : .*|Component : VexiiRiscv|Git hash  : .*)", line)
           for line in header.splitlines())
normalized = profile["generated_header"] + "\n\n" + body
restored_header = normalized != raw
normalized_raw = out / "generated.v"
normalized_raw.write_text(normalized)
assert digest(normalized_raw) == profile["generated_sha256"], "Raw generation differs beyond provenance comments"

candidate = out / "VexiiRiscv.v"
text, count = re.subn(r"  wire +execute_freeze_valid;",
                      "  (* maxfan = 16 *) wire execute_freeze_valid;", normalized)
assert count == 1
text = text.replace("= {$urandom};", "= 0;")
assert "$urandom" not in text
text, count = re.subn(r"^module VexiiRiscv \(",
    '(* altera_attribute = "-name AUTO_SHIFT_REGISTER_RECOGNITION OFF" *)\nmodule VexiiRiscv (',
    text, flags=re.M)
assert count == 1
candidate.write_text(text)
for helper in profile["helpers"]:
    checked_log(["perl", str(snapshot / "helpers" / helper), str(candidate)], out / (helper + ".log"))
assert digest(candidate) == profile["postprocessed_sha256"], "Production-compatible postprocessing differs"
checked_log(["perl", str(snapshot / "control-transform.pl"), str(candidate)], out / "control-transform.log")
assert digest(candidate) == profile["qualified_sha256"], "Final control-factored candidate differs"
manifest = {
    "profile": args.profile, "recipe_sha256": digest(snapshot / "recipe.json"),
    "command": command, "source_files_verified": len(profile["source_file_sha256"]),
    "provenance_comment_header_restored": restored_header,
    "raw_rtl_verified": True, "postprocessed_rtl_verified": True,
    "qualified_rtl_verified": True, "qualified_sha256": digest(candidate),
}
(out / "reproduction.json").write_text(json.dumps(manifest, indent=2) + "\n")
print(json.dumps(manifest), flush=True)
