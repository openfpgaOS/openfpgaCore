def dmx_note_to_fnum_block(note, fine_tune=0):
    """Replicates chocolate-doom's FrequencyForVoice() lookup.
    fine_tune is the raw OP2 byte (0..255; 0x80 = neutral). For the second
    voice of a dual-voice instrument, chocolate-doom shifts freq_index by
    (fine_tune / 2) - 64, which on a 32-steps-per-semitone scale is a
    sub-semitone detune (or up to ±2 semitones for extreme drum patches). """
    freq_index = 64 + 32 * note
    if fine_tune:
        freq_index += (fine_tune // 2) - 64
    if freq_index < 0:
        freq_index = 0
    if freq_index < 284:
        combined = DMX_FREQ_CURVE[freq_index]
    else:
        sub = (freq_index - 284) % (12 * 32)
        oct_ = (freq_index - 284) // (12 * 32)
        combined = DMX_FREQ_CURVE[sub + 284] | (oct_ << 10)
    fnum = combined & 0x3FF
    block = (combined >> 10) & 7
    return fnum, block

