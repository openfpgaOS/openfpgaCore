def convert_voice(v):
    """v is 16 bytes of DMX OP2 voice. Returns 11 bytes for our format."""
    # DMX voice layout (per chocolate-doom / DOOM wiki):
    #   [0] mod_char (trem/vib/sus/KSR/mult)  -> reg 0x20
    #   [1] mod_AD                             -> reg 0x60
    #   [2] mod_SR                             -> reg 0x80
    #   [3] mod_wave                           -> reg 0xE0
    #   [4] mod_ksl  (KSL bits 7:6 pre-shifted, rest zero)
    #   [5] mod_vol  (TL attenuation 0..63)    -> combine with [4] into reg 0x40
    #   [6] feedback (FB<<1|CNT)               -> reg 0xC0
    #   [7..12] same pattern for carrier
    #   [13] unused, [14..15] base_note_offset int16 LE
    mod_char, mod_ad, mod_sr, mod_wave, mod_ksl, mod_vol = v[0:6]
    feedback                                             = v[6]
    car_char, car_ad, car_sr, car_wave, car_ksl, car_vol = v[7:13]
    mod_scale = (mod_ksl & 0xC0) | (mod_vol & 0x3F)
    car_scale = (car_ksl & 0xC0) | (car_vol & 0x3F)
    return bytes([
        feedback,                                        # 0: FB/CNT (C0)
        mod_char, mod_scale, mod_ad, mod_sr, mod_wave,   # 1-5: mod
        car_char, car_scale, car_ad, car_sr, car_wave,   # 6-10: car
    ])

def fmt_line(name, idx, b):
    hex_ = ", ".join(f"0x{x:02X}" for x in b)
    return f"    /* {idx}: {name} */\n    {hex_},\n"

def main():
    with open('/tmp/DMXOPL/GENMIDI.op2','rb') as f:
        d = f.read()
    assert d[:8] == b'#OPL_II#', "Not an OP2 file"
    out_v1 = []
    out_v2 = []
    drum_freq_bytes_v1 = []  # (flo, fhi_blk, fixed_note, fnum, block)
    drum_freq_bytes_v2 = []
    drum_dual = []           # bool per drum: 1 if dual-voice
    for i in range(175):
        rec = d[8 + i*36 : 8 + i*36 + 36]
        flags, fine, fixed_note = struct.unpack('<HBB', rec[:4])
        v1 = rec[4:4+16]
        v2 = rec[20:20+16]
        cvt1 = convert_voice(v1)
        cvt2 = convert_voice(v2)
        is_dual = bool(flags & 0x04)
        if i < 128:
            name = GM_PROG_NAMES[i]
            out_v1.append(fmt_line(name, i, cvt1))
            out_v2.append(fmt_line(name, i, cvt2))
        else:
            drum_idx = i - 128
            gm_note = 35 + drum_idx
            name = DRUM_NAMES[drum_idx] if drum_idx < len(DRUM_NAMES) else f"Drum {gm_note}"
            label = f"{gm_note}: {name}"
            out_v1.append(fmt_line(label, i, cvt1))
            out_v2.append(fmt_line(label, i, cvt2))
            fn1, bl1 = dmx_note_to_fnum_block(fixed_note)
            fn2, bl2 = dmx_note_to_fnum_block(fixed_note, fine_tune=fine)
            drum_freq_bytes_v1.append((fn1 & 0xFF, (bl1 << 2) | ((fn1 >> 8) & 3), fixed_note, fn1, bl1))
            drum_freq_bytes_v2.append((fn2 & 0xFF, (bl2 << 2) | ((fn2 >> 8) & 3), fixed_note, fn2, bl2))
            drum_dual.append(1 if is_dual else 0)

    print("/* Generated from DMXOPL GENMIDI.op2 by tools/op2_to_bank.py */")
    print("static const uint8_t gm_bank[175 * 11] = {")
    print("    /* ---- Melodic instruments (programs 0-127) — OP2 voice1 ---- */\n")
    for line in out_v1[:128]:
        print(line, end="")
    print("\n    /* ---- Percussion (GM drum map 35-81) — OP2 voice1 ---- */\n")
    for line in out_v1[128:]:
        print(line, end="")
    print("};\n")
    print("/* Secondary OPL patch for OP2 dual-voice instruments (flag 0x04).")
    print(" * Only the drum entries (128..174) are used by the engine — melodic")
    print(" * stays single-voice so 18 OPL channels aren't exhausted by complex")
    print(" * tracks. Non-dual drums leave voice2 == voice1 (ignored at runtime). */")
    print("static const uint8_t gm_bank_v2[175 * 11] = {")
    print("    /* ---- Melodic (unused at runtime, kept for completeness) ---- */\n")
    for line in out_v2[:128]:
        print(line, end="")
    print("\n    /* ---- Percussion voice2 ---- */\n")
    for line in out_v2[128:]:
        print(line, end="")
    print("};\n")
    print("/* Drum voice1 frequency (GM note 35..81): precomputed {A0, B0-no-keyon}")
    print(" * from chocolate-doom's frequency_curve[] using each OP2 fixed_note. */")
    print("static const uint8_t gm_drum_freq[47 * 2] = {")
    for i in range(47):
        flo, fhi_blk, fn, f, b = drum_freq_bytes_v1[i]
        gm = 35 + i
        name = DRUM_NAMES[i] if i < len(DRUM_NAMES) else f"drum {gm}"
        print(f"    0x{flo:02X}, 0x{fhi_blk:02X},  /* {gm:2d} {name:16.16s} fixed={fn:3d} fnum={f:4d} blk={b} */")
    print("};\n")
    print("/* Drum voice2 frequency — same fixed_note but with the per-patch")
    print(" * fine_tune offset applied to freq_index. Used only when gm_drum_dual[i]=1. */")
    print("static const uint8_t gm_drum_freq2[47 * 2] = {")
    for i in range(47):
        flo, fhi_blk, fn, f, b = drum_freq_bytes_v2[i]
        gm = 35 + i
        name = DRUM_NAMES[i] if i < len(DRUM_NAMES) else f"drum {gm}"
        print(f"    0x{flo:02X}, 0x{fhi_blk:02X},  /* {gm:2d} {name:16.16s} fnum={f:4d} blk={b} */")
    print("};\n")
    print("/* 1 = OP2 dual-voice flag set (DMXOPL percussion often sets this to")
    print(" * stack two OPL channels per hit with a detune between them). */")
    print("static const uint8_t gm_drum_dual[47] = {")
    for i in range(0, 47, 16):
        row = ", ".join(str(n) for n in drum_dual[i:i+16])
        print(f"    {row},")
    print("};")

if __name__ == "__main__":
    main()
